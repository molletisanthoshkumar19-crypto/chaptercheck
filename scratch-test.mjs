/**
 * Diagnostic v7 — Standard syllable counting algorithm
 */

function countSyllablesStandard(word) {
  const w = word.toLowerCase().replace(/[^a-z]/g, "");
  if (w.length === 0) return 0;
  if (w.length <= 3) return 1;

  // 1. Count vowel groups including 'y'
  const vowelGroups = w.match(/[aeiouy]+/g);
  let count = vowelGroups ? vowelGroups.length : 0;

  // 2. Subtract silent 'e' at the end, but keep it if it's 'le' preceded by a consonant
  if (w.endsWith("e")) {
    if (w.endsWith("le") && w.length > 2 && !/[aeiouy]/.test(w[w.length - 3])) {
      // keep 'le' syllable (e.g., apple, table)
    } else {
      // other trailing 'e's are generally silent
      count -= 1;
    }
  }

  // 3. Fix -ed endings (waited, landed add a syllable; loved, changed do not)
  if (w.endsWith("ed") && count > 1) {
    if (!w.endsWith("ted") && !w.endsWith("ded")) {
      // If it doesn't end in ted/ded, the 'ed' is usually silent.
      // But wait, the 'e' was already subtracted by the rule above!
      // If the 'e' was already subtracted, we shouldn't subtract again.
      // Let's refine this.
    }
  }

  return Math.max(1, count);
}

function countSyllablesClean(word) {
  const w = word.toLowerCase().replace(/[^a-z]/g, "");
  if (w.length <= 3) return w.length > 0 ? 1 : 0;
  
  let count = 0;
  const vowels = "aeiouy";
  let onVowel = false;
  
  for (let i = 0; i < w.length; i++) {
    const isVowel = vowels.includes(w[i]);
    if (isVowel && !onVowel) {
      count++;
    }
    onVowel = isVowel;
  }
  
  if (w.endsWith("e")) {
    count--;
    if (w.endsWith("le") && w.length > 2 && !vowels.includes(w[w.length-3])) {
      count++;
    }
  }
  
  // Handle -ed suffix. If it doesn't end in -ted or -ded, the 'e' in 'ed' is silent.
  // We already subtracted 1 for the trailing 'e' above.
  // Wait, if word ends in "ed", it ends in "e"? No, it ends in "d"!
  // Ah, the previous rule only caught words ending EXACTLY in "e".
  
  if (w.endsWith("ed") && !w.endsWith("ted") && !w.endsWith("ded")) {
      count--;
  }
  
  // Handle 'es' (plural/verbs). Usually silent unless after s, c, g, z, x, ch, sh
  if (w.endsWith("es") && !w.endsWith("ces") && !w.endsWith("ses") && !w.endsWith("ges") && !w.endsWith("zes") && !w.endsWith("xes") && !w.endsWith("ches") && !w.endsWith("shes")) {
      count--;
  }
  
  return Math.max(1, count);
}

function extractWords(text) {
  return (text.match(/\b[a-zA-Z'-]+\b/g) || []).map(w => w.toLowerCase());
}

function splitSentences(text) {
  const normalised = text.replace(/\r\n/g, "\n").replace(/\r/g, "\n");
  const ABBREV = new Set(["mr","mrs","ms","dr","prof","sr","jr","vs","etc","e.g","i.e","fig","approx","dept","est","govt","inc","ltd","st","ave","blvd","jan","feb","mar","apr","jun","jul","aug","sep","oct","nov","dec","no","vol","pp","ed","al","rev"]);
  const raw = [];
  let start = 0;
  const re = /([.!?]+)(\s+)(?=[A-Z"'(])/g;
  let m;
  while ((m = re.exec(normalised)) !== null) {
    const endPos = m.index + m[1].length;
    const preceding = normalised.slice(0, m.index);
    const lastWord = (preceding.match(/([a-zA-Z.]+)$/) || [""])[0].toLowerCase().replace(/\.$/, "");
    if (ABBREV.has(lastWord)) continue;
    if (/\d$/.test(preceding)) continue;
    const sentence = normalised.slice(start, endPos).trim();
    if (sentence.length > 0) raw.push(sentence);
    start = endPos + m[2].length;
  }
  const tail = normalised.slice(start).trim();
  if (tail.length > 0) raw.push(tail);
  return raw.filter(s => s.replace(/\s+/g, "").length > 0);
}

const PASSAGE = `Technology has changed the way people communicate, learn, and work. Many tasks that once required hours of effort can now be completed within minutes. However, the rapid development of artificial intelligence has introduced several complicated challenges.

Although intelligent systems can process enormous amounts of information, they do not always understand the context in which that information is used. Consequently, people must carefully evaluate the recommendations generated by these systems before making important decisions.

The implementation of advanced technologies also requires substantial investment, reliable infrastructure, and appropriately trained professionals. Organizations that fail to consider these requirements may experience unexpected difficulties during deployment.

Despite these challenges, technology can improve education, healthcare, and transportation when it is implemented responsibly. The ultimate objective should not simply be to develop increasingly sophisticated machines, but to ensure that technological progress produces meaningful benefits for society.`;

const words = extractWords(PASSAGE);
const sentences = splitSentences(PASSAGE);
const ASL = words.length / sentences.length;

function score(fn) {
  const syl = words.reduce((s,w) => s + fn(w), 0);
  const ASW = syl / words.length;
  const raw = 206.835 - 1.015*ASL - 84.6*ASW;
  return { syl, ASW: ASW.toFixed(4), raw: raw.toFixed(2), score: Math.min(100, Math.max(0, Math.round(raw))) };
}

const res = score(countSyllablesClean);

console.log(`Words: ${words.length}, Sentences: ${sentences.length}, ASL: ${ASL.toFixed(2)}`);
console.log(`Syllables: ${res.syl}, ASW: ${res.ASW}`);
console.log(`Flesch Score: ${res.score} (Raw: ${res.raw})`);

